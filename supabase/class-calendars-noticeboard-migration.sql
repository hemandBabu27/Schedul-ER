-- Schedul-ER class calendars and class noticeboards
-- Run this migration in Supabase SQL Editor after backing up public.events.
-- Class routing is derived from the authenticated JWT email, never from browser input.

create or replace function public.schedul_er_class_for_email(p_email text)
returns text
language sql
immutable
set search_path = public
as $$
  select case
    when lower(trim(coalesce(p_email,''))) = 'er27@gmail.com' then '23'
    when lower(trim(coalesce(p_email,''))) = 'er28@gmail.com' then '24'
    when lower(trim(coalesce(p_email,''))) = 'er29@gmail.com' then '25'
    when lower(trim(coalesce(p_email,''))) = 'er30@gmail.com' then '26'
    when lower(trim(coalesce(p_email,''))) ~ '^23[^@]*@tkmce[.]ac[.]in$' then '23'
    when lower(trim(coalesce(p_email,''))) ~ '^24[^@]*@tkmce[.]ac[.]in$' then '24'
    when lower(trim(coalesce(p_email,''))) ~ '^25[^@]*@tkmce[.]ac[.]in$' then '25'
    when lower(trim(coalesce(p_email,''))) ~ '^26[^@]*@tkmce[.]ac[.]in$' then '26'
    else null
  end;
$$;

create or replace function public.schedul_er_is_class_admin(p_class text)
returns boolean
language sql
stable
security invoker
set search_path = public
as $$
  select
    (lower(coalesce(auth.jwt() ->> 'email','')) = 'er27@gmail.com' and p_class = '23')
    or (lower(coalesce(auth.jwt() ->> 'email','')) = 'er28@gmail.com' and p_class = '24')
    or (lower(coalesce(auth.jwt() ->> 'email','')) = 'er29@gmail.com' and p_class = '25')
    or (lower(coalesce(auth.jwt() ->> 'email','')) = 'er30@gmail.com' and p_class = '26');
$$;

alter table public.events add column if not exists class_id text;

-- Migrate legacy per-email calendars to their matching class. Unmatched rows
-- are deliberately preserved but remain inaccessible until manually assigned.
update public.events
set class_id = public.schedul_er_class_for_email(calendar_email)
where class_id is null and calendar_email is not null
  and public.schedul_er_class_for_email(calendar_email) is not null;

alter table public.events enable row level security;
drop policy if exists "calendar email can read its events" on public.events;
drop policy if exists "calendar email can insert its events" on public.events;
drop policy if exists "calendar email can update its events" on public.events;
drop policy if exists "calendar email can delete its events" on public.events;
drop policy if exists "class members can read class events" on public.events;
drop policy if exists "class admins can insert class events" on public.events;
drop policy if exists "class admins can update class events" on public.events;
drop policy if exists "class admins can delete class events" on public.events;

create policy "class members can read class events"
on public.events for select to authenticated
using (class_id = public.schedul_er_class_for_email(auth.jwt() ->> 'email'));

create policy "class admins can insert class events"
on public.events for insert to authenticated
with check (public.schedul_er_is_class_admin(class_id));

create policy "class admins can update class events"
on public.events for update to authenticated
using (public.schedul_er_is_class_admin(class_id))
with check (public.schedul_er_is_class_admin(class_id));

create policy "class admins can delete class events"
on public.events for delete to authenticated
using (public.schedul_er_is_class_admin(class_id));

create table if not exists public.notices (
  id bigint generated by default as identity primary key,
  class_id text not null check (class_id in ('23','24','25','26')),
  title text not null check (char_length(trim(title)) between 1 and 120),
  body text not null check (char_length(trim(body)) between 1 and 2000),
  author_email text not null,
  created_at timestamptz not null default now()
);

alter table public.notices enable row level security;
grant select, insert, update, delete on public.notices to authenticated;
grant usage, select on sequence public.notices_id_seq to authenticated;
drop policy if exists "class members can read notices" on public.notices;
drop policy if exists "class members can post notices" on public.notices;
drop policy if exists "class admins can update notices" on public.notices;
drop policy if exists "class admins can delete notices" on public.notices;

create policy "class members can read notices"
on public.notices for select to authenticated
using (class_id = public.schedul_er_class_for_email(auth.jwt() ->> 'email'));

create policy "class members can post notices"
on public.notices for insert to authenticated
with check (
  class_id = public.schedul_er_class_for_email(auth.jwt() ->> 'email')
  and lower(author_email) = lower(auth.jwt() ->> 'email')
);

create policy "class admins can update notices"
on public.notices for update to authenticated
using (public.schedul_er_is_class_admin(class_id))
with check (public.schedul_er_is_class_admin(class_id));

create policy "class admins can delete notices"
on public.notices for delete to authenticated
using (public.schedul_er_is_class_admin(class_id));

create index if not exists events_class_date_idx on public.events(class_id, date);
create index if not exists notices_class_created_idx on public.notices(class_id, created_at desc);

-- Enable realtime for notices if the project publication exists.
do $$
begin
  if exists (select 1 from pg_publication where pubname = 'supabase_realtime') then
    if not exists (select 1 from pg_publication_tables where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'events') then
      alter publication supabase_realtime add table public.events;
    end if;
    if not exists (select 1 from pg_publication_tables where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'notices') then
      alter publication supabase_realtime add table public.notices;
    end if;
  end if;
end $$;
