-- Schedul-ER Web Push: run once in Supabase SQL Editor.
create table if not exists public.push_subscriptions (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  class_id text not null check (class_id in ('23','24','25','26')),
  endpoint text not null unique,
  p256dh text not null, auth text not null, user_agent text,
  created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);
alter table public.push_subscriptions enable row level security;
grant select,insert,update,delete on public.push_subscriptions to authenticated;
drop policy if exists "Users manage their own push subscriptions" on public.push_subscriptions;
create policy "Users manage their own push subscriptions" on public.push_subscriptions
for all to authenticated
using (user_id=auth.uid() and class_id=public.schedul_er_class_for_email(auth.jwt()->>'email'))
with check (user_id=auth.uid() and class_id=public.schedul_er_class_for_email(auth.jwt()->>'email'));

create table if not exists public.push_queue (
  id bigint generated by default as identity primary key,
  dedupe_key text not null unique,
  class_id text not null check (class_id in ('23','24','25','26')),
  event_id text not null, notification_type text not null,
  event_title text not null, event_date date, event_time text, event_notes text, event_category text,
  created_at timestamptz not null default now(), processed_at timestamptz
);
create table if not exists public.push_delivery_log (
  id bigint generated by default as identity primary key,
  queue_id bigint not null references public.push_queue(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  sent_at timestamptz not null default now(), unique(queue_id,user_id)
);
alter table public.push_queue enable row level security;
alter table public.push_delivery_log enable row level security;
revoke all on public.push_queue,public.push_delivery_log from anon,authenticated;

create or replace function public.schedul_er_queue_event_push()
returns trigger language plpgsql security definer set search_path=public as $$
declare r record; kind text;
begin
  if tg_op='INSERT' then r:=new;kind:='new';
  elsif tg_op='UPDATE' then r:=new;kind:='updated';
  else r:=old;kind:='deleted'; end if;
  if tg_op='UPDATE' and
    (old.title,old.date,old.time,old.notes,old.category) is not distinct from
    (new.title,new.date,new.time,new.notes,new.category) then return new; end if;
  insert into public.push_queue(dedupe_key,class_id,event_id,notification_type,event_title,event_date,event_time,event_notes,event_category)
  values(gen_random_uuid()::text,r.class_id,r.id::text,kind,coalesce(r.title,'Event'),r.date,r.time,r.notes,r.category);
  if tg_op='DELETE' then return old; else return new; end if;
end; $$;
drop trigger if exists schedul_er_event_push_trigger on public.events;
create trigger schedul_er_event_push_trigger after insert or update or delete on public.events
for each row execute function public.schedul_er_queue_event_push();
create index if not exists push_subscriptions_class_idx on public.push_subscriptions(class_id);
create index if not exists push_queue_pending_idx on public.push_queue(created_at) where processed_at is null;
