-- Schedul-ER noticeboard interactions: likes, admin pinning, and polls
-- Run once in Supabase SQL Editor after the class-calendars-noticeboard migration.

alter table public.notices
  add column if not exists is_pinned boolean not null default false,
  add column if not exists poll_question text,
  add column if not exists poll_options jsonb;

create table if not exists public.notice_likes (
  id bigint generated by default as identity primary key,
  notice_id bigint not null references public.notices(id) on delete cascade,
  class_id text not null check (class_id in ('23','24','25','26')),
  user_email text not null,
  created_at timestamptz not null default now(),
  constraint notice_likes_one_per_user unique (notice_id, user_email)
);

create table if not exists public.notice_poll_votes (
  id bigint generated by default as identity primary key,
  notice_id bigint not null references public.notices(id) on delete cascade,
  class_id text not null check (class_id in ('23','24','25','26')),
  user_email text not null,
  option_index integer not null check (option_index >= 0 and option_index <= 3),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint notice_poll_one_vote_per_user unique (notice_id, user_email)
);

alter table public.notice_likes enable row level security;
alter table public.notice_poll_votes enable row level security;

grant select, insert, delete on public.notice_likes to authenticated;
grant select, insert, update on public.notice_poll_votes to authenticated;
grant usage, select on sequence public.notice_likes_id_seq to authenticated;
grant usage, select on sequence public.notice_poll_votes_id_seq to authenticated;

drop policy if exists "class members can read notice likes" on public.notice_likes;
drop policy if exists "class members can like notices" on public.notice_likes;
drop policy if exists "members can remove own notice likes" on public.notice_likes;
create policy "class members can read notice likes"
on public.notice_likes for select to authenticated
using (class_id = public.schedul_er_class_for_email(auth.jwt() ->> 'email'));
create policy "class members can like notices"
on public.notice_likes for insert to authenticated
with check (
  class_id = public.schedul_er_class_for_email(auth.jwt() ->> 'email')
  and lower(user_email) = lower(auth.jwt() ->> 'email')
  and exists (select 1 from public.notices n where n.id = notice_id and n.class_id = notice_likes.class_id)
);
create policy "members can remove own notice likes"
on public.notice_likes for delete to authenticated
using (
  class_id = public.schedul_er_class_for_email(auth.jwt() ->> 'email')
  and lower(user_email) = lower(auth.jwt() ->> 'email')
);

drop policy if exists "class members can read poll votes" on public.notice_poll_votes;
drop policy if exists "class members can cast poll votes" on public.notice_poll_votes;
drop policy if exists "members can change own poll vote" on public.notice_poll_votes;
create policy "class members can read poll votes"
on public.notice_poll_votes for select to authenticated
using (class_id = public.schedul_er_class_for_email(auth.jwt() ->> 'email'));
create policy "class members can cast poll votes"
on public.notice_poll_votes for insert to authenticated
with check (
  class_id = public.schedul_er_class_for_email(auth.jwt() ->> 'email')
  and lower(user_email) = lower(auth.jwt() ->> 'email')
  and exists (
    select 1 from public.notices n
    where n.id = notice_id and n.class_id = notice_poll_votes.class_id
      and jsonb_typeof(n.poll_options) = 'array'
      and option_index < jsonb_array_length(n.poll_options)
  )
);
create policy "members can change own poll vote"
on public.notice_poll_votes for update to authenticated
using (
  class_id = public.schedul_er_class_for_email(auth.jwt() ->> 'email')
  and lower(user_email) = lower(auth.jwt() ->> 'email')
)
with check (
  class_id = public.schedul_er_class_for_email(auth.jwt() ->> 'email')
  and lower(user_email) = lower(auth.jwt() ->> 'email')
  and exists (
    select 1 from public.notices n
    where n.id = notice_id and n.class_id = notice_poll_votes.class_id
      and jsonb_typeof(n.poll_options) = 'array'
      and option_index < jsonb_array_length(n.poll_options)
  )
);

create index if not exists notice_likes_notice_idx on public.notice_likes(notice_id);
create index if not exists notice_poll_votes_notice_idx on public.notice_poll_votes(notice_id);

